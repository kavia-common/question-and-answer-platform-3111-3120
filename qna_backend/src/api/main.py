class GenerateAnswerRequest(BaseModel):
    question_id: int = Field(..., description="Question ID to answer")
    use_ai: bool = Field(True, description="If true, generate via OpenAI; otherwise require manual body")
    body: Optional[str] = Field(None, description="Manual answer body (required if use_ai is false)")

@app.post(
    "/answers",
    response_model=AnswerOut,
    tags=["Answers"],
    summary="Create/generate answer",
    description="Create an answer for a question. If use_ai is true, the server will call OpenAI to generate an answer.",
    responses={
        400: {"description": "Bad request"},
        404: {"description": "Question not found"},
        401: {"description": "Unauthorized (if manual answer creation by user)"},
    },
)
async def create_answer(
    payload: GenerateAnswerRequest,
    current_user: Optional[dict] = Depends(lambda: None)  # Optional auth; AI answers can be anonymous
):
    """
    PUBLIC_INTERFACE
    Creates an answer. When use_ai is true, generates answer content using OpenAI Chat Completions.

    Parameters:
    - payload: GenerateAnswerRequest - question_id, use_ai, body (optional)

    Returns:
    - AnswerOut
    """
    q = next((x for x in DB["questions"] if x["id"] == payload.question_id), None)
    if not q:
        raise HTTPException(status_code=404, detail="Question not found.")

    is_ai = False
    answer_body = payload.body

    if payload.use_ai:
        is_ai = True
        prompt = f"Provide a helpful, concise answer to the following question:\n\nTitle: {q['title']}\n\nDetails: {q['body']}"
        answer_body = await call_openai_chat(prompt)
    else:
        if not answer_body:
            raise HTTPException(status_code=400, detail="Manual answer requires 'body'.")
        if current_user is None:
            raise HTTPException(status_code=401, detail="Authentication required for manual answers.")

    aid = next_id("answers")
    now = datetime.utcnow()
    ans = {
        "id": aid,
        "question_id": q["id"],
        "user_id": None if is_ai else current_user["id"],
        "body": answer_body,
        "created_at": now,
        "is_ai_generated": is_ai,
    }
    DB["answers"].append(ans)
    return AnswerOut(**ans)

@app.get(
    "/questions/{question_id}/answers",
    response_model=List[AnswerOut],
    tags=["Answers"],
    summary="List answers for a question",
    description="Retrieve all answers for a specific question."
)
async def list_answers_for_question(question_id: int):
    """
    PUBLIC_INTERFACE
    Returns answers for a given question ID.
    """
    answers = [a for a in DB["answers"] if a["question_id"] == question_id]
    answers = sorted(answers, key=lambda x: x["created_at"], reverse=True)
    return [AnswerOut(**a) for a in answers]
