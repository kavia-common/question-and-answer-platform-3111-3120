@app.post("/auth/signup", response_model=UserOut, tags=["Auth"], summary="User signup", description="Create a new user account.")
def signup(user_in: UserCreate):
    """
    PUBLIC_INTERFACE
    Signup endpoint. Creates a new user with hashed password.

    Parameters:
    - user_in: UserCreate - email, full_name, password

    Returns:
    - UserOut: id, email, full_name
    """
    if get_user_by_email(user_in.email) is not None:
        raise HTTPException(status_code=400, detail="Email already registered.")
    uid = next_id("users")
    user = {
        "id": uid,
        "email": user_in.email,
        "full_name": user_in.full_name,
        "hashed_password": get_password_hash(user_in.password),
        "created_at": datetime.utcnow(),
    }
    DB["users"].append(user)
    return {"id": user["id"], "email": user["email"], "full_name": user["full_name"]}

@app.post("/auth/login", response_model=Token, tags=["Auth"], summary="User login", description="Authenticate user and obtain JWT access token.")
def login(form_data: OAuth2PasswordRequestForm = Depends()):
    """
    PUBLIC_INTERFACE
    Login endpoint.

    Accepts:
    - OAuth2PasswordRequestForm (username=email, password)

    Returns:
    - Token: access_token, token_type
    """
    user = get_user_by_email(form_data.username)
    if not user or not verify_password(form_data.password, user["hashed_password"]):
        raise HTTPException(status_code=400, detail="Incorrect email or password.")
    access_token_expires = timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)
    token = create_access_token(data={"sub": str(user["id"])}, expires_delta=access_token_expires)
    return {"access_token": token, "token_type": "bearer"}

