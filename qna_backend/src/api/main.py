class Token(BaseModel):
    access_token: str = Field(..., description="JWT access token")
    token_type: str = Field(..., description="Type of token; typically 'bearer'")

class TokenData(BaseModel):
    user_id: Optional[int] = Field(None, description="User ID from token subject")

class UserBase(BaseModel):
    email: EmailStr = Field(..., description="User email")
    full_name: Optional[str] = Field(None, description="Full name")

class UserCreate(UserBase):
    password: str = Field(..., min_length=6, description="User password")

class UserOut(UserBase):
    id: int = Field(..., description="User identifier")

class QuestionBase(BaseModel):
    title: str = Field(..., min_length=3, max_length=200, description="Question title")
    body: str = Field(..., min_length=3, description="Question details")

class QuestionCreate(QuestionBase):
    pass

class QuestionOut(QuestionBase):
    id: int = Field(..., description="Question identifier")
    user_id: int = Field(..., description="Author user ID")
    created_at: datetime = Field(..., description="Creation timestamp")

class AnswerBase(BaseModel):
    body: str = Field(..., min_length=1, description="Answer text")

class AnswerCreate(AnswerBase):
    question_id: int = Field(..., description="Related question ID")

class AnswerOut(AnswerBase):
    id: int = Field(..., description="Answer identifier")
    question_id: int = Field(..., description="Related question ID")
    user_id: Optional[int] = Field(None, description="Author user ID (None if AI generated)")
    created_at: datetime = Field(..., description="Creation timestamp")
    is_ai_generated: bool = Field(False, description="Flag indicating if answer was generated by AI")

# =============================================================================
# Utility functions
# =============================================================================

def verify_password(plain_password: str, hashed_password: str) -> bool:
    return pwd_context.verify(plain_password, hashed_password)

def get_password_hash(password: str) -> str:
    return pwd_context.hash(password)

def create_access_token(data: dict, expires_delta: Optional[timedelta] = None) -> str:
    to_encode = data.copy()
    expire = datetime.utcnow() + (expires_delta or timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES))
    to_encode.update({"exp": expire})
    encoded_jwt = jwt.encode(to_encode, SECRET_KEY, algorithm=ALGORITHM)
    return encoded_jwt

def get_user_by_email(email: str) -> Optional[dict]:
    return next((u for u in DB["users"] if u["email"].lower() == email.lower()), None)

def get_user_by_id(user_id: int) -> Optional[dict]:
    return next((u for u in DB["users"] if u["id"] == user_id), None)

async def get_current_user(token: str = Depends(oauth2_scheme)) -> dict:
    credentials_exception = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Could not validate credentials.",
        headers={"WWW-Authenticate": "Bearer"},
    )
    try:
        payload = jwt.decode(token, SECRET_KEY, algorithms=[ALGORITHM])
        sub: Optional[int] = payload.get("sub")
        if sub is None:
            raise credentials_exception
        token_data = TokenData(user_id=int(sub))
    except JWTError:
        raise credentials_exception
    user = get_user_by_id(token_data.user_id) if token_data.user_id is not None else None
    if user is None:
        raise credentials_exception
    return user

def next_id(key: str) -> int:
    if not DB[key]:
        return 1
    return max(item["id"] for item in DB[key]) + 1

