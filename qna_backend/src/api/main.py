async def create_question(question_in: QuestionCreate, current_user: dict = Depends(get_current_user)):
    """
    PUBLIC_INTERFACE
    Creates a question associated with the authenticated user.

    Parameters:
    - question_in: QuestionCreate - title, body

    Returns:
    - QuestionOut
    """
    qid = next_id("questions")
    now = datetime.utcnow()
    q = {
        "id": qid,
        "title": question_in.title,
        "body": question_in.body,
        "user_id": current_user["id"],
        "created_at": now,
    }
    DB["questions"].append(q)
    return QuestionOut(**q)

