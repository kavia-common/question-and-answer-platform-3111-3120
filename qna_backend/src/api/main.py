async def call_openai_chat(prompt: str) -> str:
    """
    Calls OpenAI Chat Completions API to generate an answer.
    Uses OPENAI_API_KEY environment variable.
    """
    if not OPENAI_API_KEY:
        # Provide a helpful error to operator; API still responds gracefully.
        raise HTTPException(
            status_code=500,
            detail="OPENAI_API_KEY is not set. Please configure it in the environment."
        )

    # Using the new Responses API would be possible, but we'll use chat completions for compatibility.
    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {OPENAI_API_KEY}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": "gpt-4o-mini",
        "messages": [
            {"role": "system", "content": "You are a helpful assistant for a Q&A application."},
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.2,
    }

    async with httpx.AsyncClient(timeout=60.0) as client:
        resp = await client.post(url, headers=headers, json=payload)
        if resp.status_code >= 400:
            raise HTTPException(status_code=resp.status_code, detail=f"OpenAI error: {resp.text}")
        data = resp.json()
        content = data["choices"][0]["message"]["content"]
        return content.strip()

